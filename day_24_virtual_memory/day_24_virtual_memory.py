@dataclass
class TLBEntry:
    frame_number: int
    writable: bool
    executable: bool


class TLB:
    """
    Small LRU translation cache.

    Real hardware TLBs are implemented in specialized hardware, but this
    OrderedDict model makes the replacement behavior easy to study.
    """

    def __init__(self, capacity: int):
        if capacity <= 0:
            raise ValueError("TLB capacity must be positive.")

        self.capacity = capacity
        self.entries: OrderedDict[int, TLBEntry] = OrderedDict()
        self.hits = 0
        self.misses = 0

    def lookup(self, page_number: int) -> Optional[TLBEntry]:
        entry = self.entries.get(page_number)

        if entry is None:
            self.misses += 1
            return None

        self.hits += 1
        self.entries.move_to_end(page_number)
        return entry

    def insert(self, page_number: int, entry: TLBEntry) -> None:
        self.entries[page_number] = entry
        self.entries.move_to_end(page_number)

        if len(self.entries) > self.capacity:
            self.entries.popitem(last=False)

    def invalidate(self, page_number: Optional[int] = None) -> None:
        if page_number is None:
            self.entries.clear()
        else:
            self.entries.pop(page_number, None)

    @property
    def hit_rate(self) -> float:
        total = self.hits + self.misses
        return self.hits / total if total else 0.0


def demonstrate_tlb() -> None:
    print_section("4. Translation Lookaside Buffer")

    tlb = TLB(capacity=2)

    translations = {
        1: TLBEntry(8, True, False),
        2: TLBEntry(3, True, False),
        3: TLBEntry(9, False, True),
    }

    for page_number in [1, 2, 1, 3, 1, 2]:
        result = tlb.lookup(page_number)

        if result:
            print(f"VPN {page_number}: TLB HIT -> frame {result.frame_number}")
        else:
            print(f"VPN {page_number}: TLB MISS")
            tlb.insert(page_number, translations[page_number])

    print(f"TLB hits   : {tlb.hits}")
    print(f"TLB misses : {tlb.misses}")
    print(f"Hit rate   : {tlb.hit_rate:.2%}")


