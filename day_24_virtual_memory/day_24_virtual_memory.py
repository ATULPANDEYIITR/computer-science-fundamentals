# SECTION 12: COPY-ON-WRITE
# ============================================================================

@dataclass
class SharedPage:
    frame_number: int
    reference_count: int = 1


class CopyOnWriteManager:
    """
    Small conceptual simulation of copy-on-write.

    Parent and child initially reference the same physical frame. A write by
    either process causes a private copy when the page is shared.
    """

    def __init__(self):
        self.next_frame = 0
        self.pages: Dict[Tuple[str, int], SharedPage] = {}

    def allocate(self, process: str, virtual_page: int) -> None:
        frame = self.next_frame
        self.next_frame += 1
        self.pages[(process, virtual_page)] = SharedPage(frame)

    def fork_share(
        self,
        parent: str,
        child: str,
        virtual_page: int,
    ) -> None:
        parent_key = (parent, virtual_page)

        if parent_key not in self.pages:
            raise ValueError("Parent page does not exist.")

        shared = self.pages[parent_key]
        shared.reference_count += 1
        self.pages[(child, virtual_page)] = shared

    def write(self, process: str, virtual_page: int) -> int:
        key = (process, virtual_page)

        if key not in self.pages:
            raise ValueError("Process page does not exist.")

        page = self.pages[key]

        if page.reference_count > 1:
            page.reference_count -= 1

            new_page = SharedPage(self.next_frame)
            self.next_frame += 1

            self.pages[key] = new_page
            page = new_page

        return page.frame_number


def demonstrate_copy_on_write() -> None:
    print_section("12. Copy-on-Write")

    manager = CopyOnWriteManager()
    manager.allocate("parent", 0)
    manager.fork_share("parent", "child", 0)

    print(
        "Before child write:",
        "parent frame =", manager.pages[("parent", 0)].frame_number,
        "child frame =", manager.pages[("child", 0)].frame_number,
    )

    manager.write("child", 0)

    print(
        "After child write:",
        "parent frame =", manager.pages[("parent", 0)].frame_number,
        "child frame =", manager.pages[("child", 0)].frame_number,
    )

    print(
        "The physical frame is shared until a write requires private state."
    )


