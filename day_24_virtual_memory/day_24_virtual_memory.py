def calculate_page_components(
    virtual_address: int,
    page_size: int,
    virtual_address_bits: int,
) -> Tuple[int, int, int]:
    """Return page number, offset, and maximum virtual address."""
    if page_size <= 0 or page_size & (page_size - 1):
        raise ValueError("Page size must be a positive power of two.")

    if virtual_address < 0:
        raise ValueError("Virtual address cannot be negative.")

    maximum_address = (1 << virtual_address_bits) - 1

    if virtual_address > maximum_address:
        raise ValueError("Virtual address exceeds the configured address space.")

    page_number = virtual_address // page_size
    offset = virtual_address % page_size
    return page_number, offset, maximum_address


