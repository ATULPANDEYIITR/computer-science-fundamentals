@dataclass
class Frame:
    frame_number: int
    page_number: Optional[int] = None
    process_id: Optional[int] = None
    dirty: bool = False
    referenced: bool = False


@dataclass
class AccessResult:
    virtual_address: int
    physical_address: Optional[int]
    page_number: int
    offset: int
    tlb_hit: bool
    page_fault: bool
    evicted_page: Optional[int]
    message: str


class PagedMemorySystem:
    """
    Integrated virtual-memory simulator.

    It models:
      - virtual pages
      - physical frames
      - a page table
      - a TLB
      - page faults
      - FIFO/LRU page replacement
      - dirty pages
      - access permissions
    """

    def __init__(
        self,
        virtual_pages: int,
        physical_frames: int,
        page_size: int = 256,
        tlb_capacity: int = 4,
        replacement_policy: str = "LRU",
    ):
        if virtual_pages <= 0:
            raise ValueError("virtual_pages must be positive.")
        if physical_frames <= 0:
            raise ValueError("physical_frames must be positive.")
        if page_size <= 0 or page_size & (page_size - 1):
            raise ValueError("page_size must be a power of two.")

        policy = replacement_policy.upper()

        if policy not in {"FIFO", "LRU", "CLOCK"}:
            raise ValueError("Replacement policy must be FIFO, LRU, or CLOCK.")

        self.virtual_pages = virtual_pages
        self.physical_frames = physical_frames
        self.page_size = page_size
        self.replacement_policy = policy

        self.page_table: Dict[int, PageTableEntry] = {
            page: PageTableEntry() for page in range(virtual_pages)
        }

        self.frames = [Frame(i) for i in range(physical_frames)]
        self.tlb = TLB(tlb_capacity)

        self.fifo_queue: deque[int] = deque()
        self.lru_order: OrderedDict[int, None] = OrderedDict()
        self.clock_hand = 0

        self.page_faults = 0
        self.memory_accesses = 0
        self.disk_reads = 0
        self.disk_writes = 0

    def access(
        self,
        virtual_address: int,
        write: bool = False,
        execute: bool = False,
    ) -> AccessResult:
        self.memory_accesses += 1

        page_number = virtual_address // self.page_size
        offset = virtual_address % self.page_size

        if not 0 <= page_number < self.virtual_pages:
            raise ValueError("Virtual address is outside the process address space.")

        tlb_entry = self.tlb.lookup(page_number)

        if tlb_entry is not None:
            if write and not tlb_entry.writable:
                raise PermissionError("Write access denied by TLB permissions.")
            if execute and not tlb_entry.executable:
                raise PermissionError("Execution denied by TLB permissions.")

            frame_number = tlb_entry.frame_number
            self._mark_frame_used(frame_number)
            return AccessResult(
                virtual_address,
                frame_number * self.page_size + offset,
                page_number,
                offset,
                True,
                False,
                None,
                "TLB hit",
            )

        page_entry = self.page_table[page_number]

        if not page_entry.present:
            self.page_faults += 1
            evicted_page = self._handle_page_fault(page_number)
            page_entry = self.page_table[page_number]

            self.tlb.insert(
                page_number,
                TLBEntry(
                    page_entry.frame_number,  # type: ignore
                    page_entry.writable,
                    page_entry.executable,
                ),
            )

            if write:
                page_entry.dirty = True

            if execute and not page_entry.executable:
                raise PermissionError("Execution denied by page table.")

            physical_address = (
                page_entry.frame_number * self.page_size + offset  # type: ignore
            )

            return AccessResult(
                virtual_address,
                physical_address,
                page_number,
                offset,
                False,
                True,
                evicted_page,
                "Page fault handled and translation installed",
            )

        if write and not page_entry.writable:
            raise PermissionError("Write access denied by page table.")

        if execute and not page_entry.executable:
            raise PermissionError("Execution denied by page table.")

        page_entry.referenced = True

        if write:
            page_entry.dirty = True

        frame_number = page_entry.frame_number
        self.tlb.insert(
            page_number,
            TLBEntry(
                frame_number,  # type: ignore
                page_entry.writable,
                page_entry.executable,
            ),
        )

        self._mark_frame_used(frame_number)  # type: ignore

        return AccessResult(
            virtual_address,
            frame_number * self.page_size + offset,  # type: ignore
            page_number,
            offset,
            False,
            False,
            None,
            "Page-table translation",
        )

    def _handle_page_fault(self, page_number: int) -> Optional[int]:
        free_frame = next(
            (frame for frame in self.frames if frame.page_number is None),
            None,
        )

        if free_frame is not None:
            frame = free_frame
            evicted_page = None
        else:
            frame = self._choose_victim()
            evicted_page = frame.page_number

            if evicted_page is not None:
                victim_entry = self.page_table[evicted_page]

                if victim_entry.dirty:
                    self.disk_writes += 1

                victim_entry.present = False
                victim_entry.frame_number = None
                victim_entry.dirty = False
                victim_entry.referenced = False

                self.tlb.invalidate(evicted_page)
                self.lru_order.pop(evicted_page, None)

        self.disk_reads += 1

        frame.page_number = page_number
        frame.dirty = False
        frame.referenced = True

        entry = self.page_table[page_number]
        entry.present = True
        entry.frame_number = frame.frame_number
        entry.referenced = True
        entry.dirty = False

        self.fifo_queue.append(frame.frame_number)
        self.lru_order[page_number] = None

        return evicted_page

    def _choose_victim(self) -> Frame:
        if self.replacement_policy == "FIFO":
            frame_number = self.fifo_queue.popleft()
            return self.frames[frame_number]

        if self.replacement_policy == "LRU":
            victim_page, _ = self.lru_order.popitem(last=False)
            frame_number = self.page_table[victim_page].frame_number
            if frame_number is None:
                raise RuntimeError("LRU metadata is inconsistent.")
            return self.frames[frame_number]

        # CLOCK / second-chance replacement.
        while True:
            frame = self.frames[self.clock_hand]

            if not frame.referenced:
                self.clock_hand = (self.clock_hand + 1) % len(self.frames)
                return frame

            frame.referenced = False

            if frame.page_number is not None:
                self.page_table[frame.page_number].referenced = False

            self.clock_hand = (self.clock_hand + 1) % len(self.frames)

    def _mark_frame_used(self, frame_number: int) -> None:
        frame = self.frames[frame_number]
        frame.referenced = True

        if frame.page_number is None:
            return

        page_number = frame.page_number

        if self.replacement_policy == "LRU":
            self.lru_order.pop(page_number, None)
            self.lru_order[page_number] = None

        self.page_table[page_number].referenced = True

    def print_state(self) -> None:
        print("\nPage table:")
        for page in range(self.virtual_pages):
            entry = self.page_table[page]
            if entry.present:
                print(
                    f"  VPN {page:2} -> frame {entry.frame_number:2} | "
                    f"dirty={entry.dirty} referenced={entry.referenced}"
                )
            else:
                print(f"  VPN {page:2} -> not resident")

        print("\nPhysical frames:")
        for frame in self.frames:
            print(
                f"  Frame {frame.frame_number:2}: "
                f"VPN={frame.page_number} dirty={frame.dirty} "
                f"referenced={frame.referenced}"
            )

    def statistics(self) -> Dict[str, float]:
        accesses = self.memory_accesses

        return {
            "memory_accesses": accesses,
            "page_faults": self.page_faults,
            "page_fault_rate": self.page_faults / accesses if accesses else 0.0,
            "tlb_hits": self.tlb.hits,
            "tlb_misses": self.tlb.misses,
            "tlb_hit_rate": self.tlb.hit_rate,
            "disk_reads": self.disk_reads,
            "disk_writes": self.disk_writes,
        }


