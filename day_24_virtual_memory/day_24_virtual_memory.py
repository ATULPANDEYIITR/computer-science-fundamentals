# SECTION 10: PAGE REPLACEMENT ALGORITHMS
# ============================================================================

def fifo_page_faults(reference_string: List[int], frame_count: int) -> int:
    """Classic FIFO page-replacement simulation."""
    if frame_count <= 0:
        raise ValueError("Frame count must be positive.")

    frames: List[int] = []
    queue: deque[int] = deque()
    faults = 0

    for page in reference_string:
        if page in frames:
            continue

        faults += 1

        if len(frames) < frame_count:
            frames.append(page)
            queue.append(page)
        else:
            victim = queue.popleft()
            frames[frames.index(victim)] = page
            queue.append(page)

    return faults


def lru_page_faults(reference_string: List[int], frame_count: int) -> int:
    """LRU replacement based on most-recently-used order."""
    if frame_count <= 0:
        raise ValueError("Frame count must be positive.")

    frames: OrderedDict[int, None] = OrderedDict()
    faults = 0

    for page in reference_string:
        if page in frames:
            frames.move_to_end(page)
            continue

        faults += 1

        if len(frames) == frame_count:
            frames.popitem(last=False)

        frames[page] = None

    return faults


def optimal_page_faults(reference_string: List[int], frame_count: int) -> int:
    """
    The theoretical optimal algorithm.

    It replaces the page whose next use is farthest in the future.
    Real operating systems cannot know the future exactly, so this is mainly
    a comparison baseline.
    """
    if frame_count <= 0:
        raise ValueError("Frame count must be positive.")

    frames: List[int] = []
    faults = 0

    for index, page in enumerate(reference_string):
        if page in frames:
            continue

        faults += 1

        if len(frames) < frame_count:
            frames.append(page)
            continue

        future = reference_string[index + 1:]
        distances = []

        for resident in frames:
            try:
                distance = future.index(resident)
            except ValueError:
                distance = float("inf")
            distances.append(distance)

        victim_index = distances.index(max(distances))
        frames[victim_index] = page

    return faults


def demonstrate_replacement_algorithms() -> None:
    print_section("10. Page Replacement Algorithms")

    reference_string = [7, 0, 1, 2, 0, 3, 0, 4, 2, 3, 0, 3, 2]

    print("Reference string:", reference_string)

    for frames in [2, 3, 4]:
        fifo = fifo_page_faults(reference_string, frames)
        lru = lru_page_faults(reference_string, frames)
        optimal = optimal_page_faults(reference_string, frames)

        print(
            f"Frames={frames}: "
            f"FIFO faults={fifo}, "
            f"LRU faults={lru}, "
            f"Optimal faults={optimal}"
        )

    print(
        "\nImportant distinction: the TLB replacement policy and the physical-page "
        "replacement policy solve different caching problems."
    )


