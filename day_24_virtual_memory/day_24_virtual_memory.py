@dataclass
class PageTableEntry:
    frame_number: Optional[int] = None
    present: bool = False
    writable: bool = True
    executable: bool = False
    user_accessible: bool = True
    referenced: bool = False
    dirty: bool = False


class SimplePageTable:
    """A basic single-level page table."""

    def __init__(self, virtual_pages: int, physical_frames: int):
        if virtual_pages <= 0 or physical_frames <= 0:
            raise ValueError("Memory sizes must be positive.")

        self.entries = [PageTableEntry() for _ in range(virtual_pages)]
        self.physical_frames = physical_frames
        self.free_frames = deque(range(physical_frames))

    def map_page(
        self,
        page_number: int,
        writable: bool = True,
        executable: bool = False,
    ) -> int:
        self._validate_page(page_number)

        entry = self.entries[page_number]

        if entry.present:
            return entry.frame_number  # type: ignore

        if not self.free_frames:
            raise MemoryError("No physical frames are available.")

        frame = self.free_frames.popleft()

        entry.frame_number = frame
        entry.present = True
        entry.writable = writable
        entry.executable = executable

        return frame

    def unmap_page(self, page_number: int) -> None:
        self._validate_page(page_number)

        entry = self.entries[page_number]

        if entry.present and entry.frame_number is not None:
            self.free_frames.append(entry.frame_number)

        self.entries[page_number] = PageTableEntry()

    def translate(self, page_number: int, offset: int, page_size: int) -> int:
        self._validate_page(page_number)

        if not 0 <= offset < page_size:
            raise ValueError("Offset is outside the page.")

        entry = self.entries[page_number]

        if not entry.present or entry.frame_number is None:
            raise PageFault(page_number)

        entry.referenced = True
        return entry.frame_number * page_size + offset

    def _validate_page(self, page_number: int) -> None:
        if not 0 <= page_number < len(self.entries):
            raise ValueError("Virtual page number is outside the page table.")


class PageFault(Exception):
    """Exception representing a simulated page fault."""

    def __init__(self, page_number: int):
        super().__init__(f"Page fault on virtual page {page_number}")
        self.page_number = page_number


def demonstrate_single_level_page_table() -> None:
    print_section("3. Single-Level Page Table")

    page_size = 256
    table = SimplePageTable(virtual_pages=8, physical_frames=4)

    table.map_page(0, writable=False, executable=True)
    table.map_page(2, writable=True)
    table.map_page(5, writable=True)

    for page_number, entry in enumerate(table.entries):
        if entry.present:
            print(
                f"VPN {page_number:2} -> PFN {entry.frame_number:2} | "
                f"present={entry.present} | writable={entry.writable} | "
                f"executable={entry.executable}"
            )

    try:
        physical_address = table.translate(2, 17, page_size)
        print(f"\nVirtual page 2, offset 17 -> physical address {physical_address}")
    except PageFault as fault:
        print(fault)

    try:
        table.translate(4, 0, page_size)
    except PageFault as fault:
        print(f"Expected exception: {fault}")


