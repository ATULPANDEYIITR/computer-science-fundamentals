@dataclass
class Segment:
    name: str
    base: int
    limit: int
    readable: bool = True
    writable: bool = False
    executable: bool = False

    def translate(self, offset: int, write: bool = False, execute: bool = False) -> int:
        if offset < 0 or offset >= self.limit:
            raise MemoryError(
                f"Segmentation fault: offset {offset} exceeds segment '{self.name}'."
            )

        if write and not self.writable:
            raise PermissionError(
                f"Write denied for segment '{self.name}'."
            )

        if execute and not self.executable:
            raise PermissionError(
                f"Execution denied for segment '{self.name}'."
            )

        return self.base + offset


class SegmentedMemory:
    """Simple logical-address to physical-address segmentation model."""

    def __init__(self):
        self.segments: Dict[int, Segment] = {}

    def add_segment(self, selector: int, segment: Segment) -> None:
        if selector < 0:
            raise ValueError("Segment selector cannot be negative.")
        self.segments[selector] = segment

    def translate(
        self,
        selector: int,
        offset: int,
        write: bool = False,
        execute: bool = False,
    ) -> int:
        if selector not in self.segments:
            raise MemoryError("Invalid segment selector.")

        return self.segments[selector].translate(offset, write, execute)


